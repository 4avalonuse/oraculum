import test from 'node:test';
import assert from 'node:assert/strict';
import { validateModelTwoWays } from '../src/analysis/model-validation.js';

const referenceModel = () => ({
  available: true,
  auditDesign: {
    x: [[1,0],[1,1],[1,2],[1,3],[1,4]],
    y: [1,2,2,4,3]
  },
  coefficients: [
    { name: 'Intercepto', beta: 1.2 },
    { name: 'x', beta: 0.6 }
  ],
  fitted: [1.2,1.8,2.4,3.0,3.6],
  residuals: [-0.2,0.2,-0.4,1.0,-0.6],
  sse: 1.6,
  r2: 0.6923076923076923,
  hacLag: 1,
  hacCoefficients: [
    { name: 'Intercepto', hacSe: 0.206559111797729 },
    { name: 'x', hacSe: 0.150554530541816 }
  ]
});

test('OLS and Newey–West/HAC agree with fixed reference values, not generated by the production estimator', () => {
  const model = referenceModel();
  const result = validateModelTwoWays(model);
  assert.equal(result.status, 'BOTH_PATHS_AGREE', JSON.stringify(result.checks));
  assert.equal(result.passed, 6);
  assert.equal(result.total, 6);
  assert.equal(result.independentlyValidated, false);
  assert.equal(result.externalReferenceValidation, 'PENDING');
});

test('reference cross-check flags a deliberately corrupted OLS coefficient', () => {
  const model = referenceModel();
  model.coefficients[1].beta = 0.9;
  const result = validateModelTwoWays(model);
  assert.equal(result.status, 'ALERT');
  assert.ok(result.checks.some(check => check.name === 'OLS coeficientes' && check.status === 'FAIL'));
});

test('reference cross-check flags a deliberately corrupted HAC standard error', () => {
  const model = referenceModel();
  model.hacCoefficients[0].hacSe = 0.9;
  const result = validateModelTwoWays(model);
  assert.equal(result.status, 'ALERT');
  assert.ok(result.checks.some(check => check.name === 'HAC erros-padrão Newey–West' && check.status === 'FAIL'));
});
